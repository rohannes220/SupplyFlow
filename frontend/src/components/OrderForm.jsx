import { useId, useRef, useState } from 'react';
import { validateOrder } from '@supplyflow/shared/orderRules';
import { US_STATES, US_TERRITORIES } from '@supplyflow/shared/usLocations';
import { ApiError } from '../services/orderApi.js';
import { EMPTY_ORDER_FORM, errorsByField, formToOrderInput } from '../utils/orderForm.js';

const FIELD_ORDER = [
  'vendorId',
  'orderAmount',
  'customerName',
  'customerCity',
  'customerState',
  'customerPhone',
];

const byName = ([, a], [, b]) => a.localeCompare(b);
const STATE_OPTIONS = Object.entries(US_STATES).sort(byName);
const TERRITORY_OPTIONS = Object.entries(US_TERRITORIES).sort(byName);

const inputClass = (invalid) =>
  `block w-full rounded-md border px-3 py-2 text-sm text-slate-900 shadow-sm placeholder:text-slate-400 focus:outline-none focus:ring-2 ${
    invalid
      ? 'border-red-500 focus:border-red-500 focus:ring-red-200'
      : 'border-slate-300 focus:border-blue-500 focus:ring-blue-200'
  }`;

function Field({ id, label, hint, error, required = true, children }) {
  return (
    <div>
      <label htmlFor={id} className="mb-1 block text-sm font-medium text-slate-700">
        {label}
        {required && (
          <span aria-hidden="true" className="text-red-600">
            {' '}
            *
          </span>
        )}
      </label>
      {children}
      {error ? (
        <p id={`${id}-error`} className="mt-1 text-sm text-red-600">
          {error}
        </p>
      ) : (
        hint && (
          <p id={`${id}-hint`} className="mt-1 text-xs text-slate-500">
            {hint}
          </p>
        )
      )}
    </div>
  );
}

export default function OrderForm({ onSubmit, onCancel }) {
  const idPrefix = useId();
  const formRef = useRef(null);
  const [form, setForm] = useState(EMPTY_ORDER_FORM);
  const [errors, setErrors] = useState({});
  const [attempted, setAttempted] = useState(false);
  const [serverError, setServerError] = useState('');
  const [submitting, setSubmitting] = useState(false);

  const id = (field) => `${idPrefix}-${field}`;

  function fieldProps(field) {
    const error = errors[field];
    return {
      id: id(field),
      name: field,
      value: form[field],
      required: true,
      'aria-invalid': error ? 'true' : 'false',
      'aria-describedby': error ? `${id(field)}-error` : `${id(field)}-hint`,
      className: inputClass(Boolean(error)),
      onChange: (event) => {
        const next = { ...form, [field]: event.target.value };
        setForm(next);
        // After the first submit attempt, re-check as the user types.
        if (attempted) setErrors(errorsByField(validateOrder(formToOrderInput(next)).errors));
      },
    };
  }

  function focusFirstError(fieldErrors) {
    const first = FIELD_ORDER.find((field) => fieldErrors[field]);
    if (first) formRef.current?.querySelector(`[name="${first}"]`)?.focus();
  }

  async function handleSubmit(event) {
    event.preventDefault();
    setAttempted(true);
    setServerError('');

    const { value, errors: list } = validateOrder(formToOrderInput(form));
    const fieldErrors = errorsByField(list);
    setErrors(fieldErrors);
    if (list.length > 0) {
      focusFirstError(fieldErrors);
      return;
    }

    setSubmitting(true);
    try {
      await onSubmit(value);
    } catch (err) {
      const serverFieldErrors =
        err instanceof ApiError
          ? errorsByField(err.details.filter((d) => FIELD_ORDER.includes(d.field)))
          : {};
      if (Object.keys(serverFieldErrors).length > 0) {
        setErrors(serverFieldErrors);
        focusFirstError(serverFieldErrors);
      } else {
        setServerError(err.message || 'Something went wrong. Please try again.');
      }
    } finally {
      setSubmitting(false);
    }
  }

  const errorCount = Object.keys(errors).length;

  return (
    <form ref={formRef} onSubmit={handleSubmit} noValidate className="space-y-5">
      {serverError && (
        <div
          role="alert"
          className="rounded-md border border-red-200 bg-red-50 px-4 py-3 text-sm text-red-700"
        >
          {serverError}
        </div>
      )}
      <p aria-live="polite" className={errorCount ? 'text-sm font-medium text-red-600' : 'sr-only'}>
        {errorCount
          ? `Please fix ${errorCount} highlighted ${errorCount === 1 ? 'field' : 'fields'}.`
          : ''}
      </p>

      <fieldset className="grid gap-4 sm:grid-cols-2">
        <legend className="mb-2 text-sm font-semibold text-slate-900">Order</legend>
        <Field
          id={id('orderId')}
          label="Order ID"
          required={false}
          hint="Generated by the system when the order is saved"
        >
          <input
            id={id('orderId')}
            value="Assigned automatically"
            readOnly
            aria-describedby={`${id('orderId')}-hint`}
            className={`${inputClass(false)} cursor-not-allowed bg-slate-100 text-slate-500`}
          />
        </Field>
        <Field
          id={id('vendorId')}
          label="Vendor ID"
          hint="Enter the ID of an active vendor"
          error={errors.vendorId}
        >
          <input
            {...fieldProps('vendorId')}
            inputMode="numeric"
            autoComplete="off"
            autoFocus
            placeholder="3"
          />
        </Field>
        <Field
          id={id('orderAmount')}
          label="Order Amount (USD)"
          hint="Greater than $0, up to 2 decimal places"
          error={errors.orderAmount}
        >
          <div className="relative">
            <span
              aria-hidden="true"
              className="pointer-events-none absolute inset-y-0 left-3 flex items-center text-sm text-slate-500"
            >
              $
            </span>
            <input
              {...fieldProps('orderAmount')}
              inputMode="decimal"
              autoComplete="off"
              placeholder="0.00"
              className={`${inputClass(Boolean(errors.orderAmount))} pl-7`}
            />
          </div>
        </Field>
      </fieldset>

      <fieldset className="grid gap-4 sm:grid-cols-2">
        <legend className="mb-2 text-sm font-semibold text-slate-900">Customer (US only)</legend>
        <Field
          id={id('customerName')}
          label="Customer Name"
          hint="Up to 100 characters"
          error={errors.customerName}
        >
          <input
            {...fieldProps('customerName')}
            autoComplete="name"
            maxLength={120}
            placeholder="Sarah Chen"
          />
        </Field>
        <Field
          id={id('customerPhone')}
          label="Customer Phone Number"
          hint="10-digit US number, e.g. (404) 555-0123"
          error={errors.customerPhone}
        >
          <input
            {...fieldProps('customerPhone')}
            type="tel"
            autoComplete="tel-national"
            placeholder="(404) 555-0123"
          />
        </Field>
        <Field
          id={id('customerCity')}
          label="Customer City"
          hint="Up to 100 characters"
          error={errors.customerCity}
        >
          <input
            {...fieldProps('customerCity')}
            autoComplete="address-level2"
            maxLength={120}
            placeholder="Atlanta"
          />
        </Field>
        <Field
          id={id('customerState')}
          label="Customer State / Territory"
          hint="International orders are not accepted"
          error={errors.customerState}
        >
          <select {...fieldProps('customerState')} autoComplete="address-level1">
            <option value="">Select a state or territory</option>
            <optgroup label="States and DC">
              {STATE_OPTIONS.map(([code, name]) => (
                <option key={code} value={code}>
                  {name} ({code})
                </option>
              ))}
            </optgroup>
            <optgroup label="US territories">
              {TERRITORY_OPTIONS.map(([code, name]) => (
                <option key={code} value={code}>
                  {name} ({code})
                </option>
              ))}
            </optgroup>
          </select>
        </Field>
      </fieldset>

      <div className="flex flex-col-reverse gap-3 border-t border-slate-200 pt-4 sm:flex-row sm:justify-end">
        <button
          type="button"
          onClick={onCancel}
          className="rounded-md border border-slate-300 bg-white px-4 py-2 text-sm font-medium text-slate-700 hover:bg-slate-50 focus:outline-none focus-visible:ring-2 focus-visible:ring-blue-500"
        >
          Cancel
        </button>
        <button
          type="submit"
          disabled={submitting}
          className="rounded-md bg-blue-600 px-4 py-2 text-sm font-medium text-white hover:bg-blue-700 focus:outline-none focus-visible:ring-2 focus-visible:ring-blue-500 focus-visible:ring-offset-2 disabled:opacity-60"
        >
          {submitting ? 'Adding…' : 'Add Order'}
        </button>
      </div>
    </form>
  );
}
